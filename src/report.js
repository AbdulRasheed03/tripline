// Incident report in Markdown, ready to paste into a ticket (Jira, ServiceNow, GitHub issue).
// Pure function of a detector snapshot, so the CLI, the server and the browser demo all produce the same report.
// Everything that came from an attacker is neutralised: no backticks, pipes or newlines, and always inside a code span,
// so a hostile username or URL cannot inject links, images or fake sections into the ticket.

import { SEVERITY_RANK, fmtSpan, VERSION } from './engine.js';

const safe = (v, max = 160) => {
  const s = String(v ?? '').replace(/[`|\r\n\t]/g, ' ').replace(/\s+/g, ' ').trim();
  return s.length > max ? s.slice(0, max) + '...' : s;
};
const code = (v, max) => '`' + (safe(v, max) || '-') + '`';
const iso = (ts) => (ts ? new Date(ts).toISOString().replace('.000Z', 'Z') : '-');
// A Windows lockout names the caller computer, not an address.
const source = (a) => a.ip || (a.host ? `host ${a.host}` : '');
const mitreLink = (id) => (id ? `[${id}](https://attack.mitre.org/techniques/${id.replace('.', '/')}/)` : '-');

export function toMarkdown(snapshot, meta = {}) {
  const alerts = [...(snapshot.alerts || [])].sort((a, b) => SEVERITY_RANK[b.severity] - SEVERITY_RANK[a.severity] || a.firstSeen - b.firstSeen);
  const counts = { critical: 0, high: 0, medium: 0, low: 0 };
  alerts.forEach((a) => { if (a.severity in counts) counts[a.severity]++; });
  const worst = alerts[0]?.severity || 'none';
  const first = Math.min(...alerts.map((a) => a.firstSeen));
  const last = Math.max(...alerts.map((a) => a.lastSeen));
  const s = snapshot.stats || {};
  const L = [];

  L.push(`# Incident report: ${alerts.length ? `${alerts.length} alert(s), highest severity ${worst}` : 'no alerts'}`);
  L.push('');
  L.push(`Generated by Tripline ${VERSION} at ${iso(meta.generatedAt || Date.now())}${meta.source ? ` from ${code(meta.source, 120)}` : ''}.`);
  L.push('');
  L.push('## Summary');
  L.push('');
  L.push('| | |');
  L.push('|:--|:--|');
  L.push(`| Alerts | ${counts.critical} critical, ${counts.high} high, ${counts.medium} medium, ${counts.low} low |`);
  if (alerts.length) L.push(`| Activity window | ${iso(first)} to ${iso(last)} (${fmtSpan(last - first)}) |`);
  if (s.auth || s.blockedAttempts) L.push(`| Login attempts | ${s.auth || 0} (${s.failures || 0} failed, ${s.successes || 0} succeeded, ${s.blockedAttempts || 0} turned away) |`);
  if (s.http) L.push(`| Web requests | ${s.http} |`);
  if (s.conns) L.push(`| Decoy connections | ${s.conns} |`);
  if (s.lockouts) L.push(`| Windows account lockouts | ${s.lockouts} |`);
  L.push(`| Sources involved | ${new Set(alerts.map((a) => a.ip).filter(Boolean)).size} |`);
  L.push('');

  if (counts.critical) {
    L.push('> **Act first:** at least one alert is critical. Disable the affected accounts or sessions before investigating further.');
    L.push('');
  }

  if (alerts.length) {
    L.push('## Alerts');
    L.push('');
    L.push('| # | Severity | Alert | Source | MITRE ATT&CK | First seen |');
    L.push('|:--|:--|:--|:--|:--|:--|');
    alerts.forEach((a, i) => L.push(`| ${i + 1} | ${a.severity} | ${safe(a.title)} | ${code(source(a), 45)} | ${mitreLink(a.mitre)} | ${iso(a.firstSeen)} |`));
    L.push('');
    alerts.forEach((a, i) => {
      L.push(`### ${i + 1}. ${safe(a.title)} (${a.severity})`);
      L.push('');
      L.push(`* **Source:** ${code(source(a), 45)}${a.user ? `, account ${code(a.user, 60)}` : ''}`);
      L.push(`* **Technique:** ${mitreLink(a.mitre)} (${a.tactic})`);
      L.push(`* **Seen:** ${iso(a.firstSeen)} to ${iso(a.lastSeen)}${a.hits > 1 ? `, matched ${a.hits} times` : ''}`);
      L.push(`* **What happened:** ${code(a.detail, 220)}`);
      if (a.evidence) L.push(`* **Evidence:** ${code(a.evidence, 220)}`);
      L.push(`* **Why it matters:** ${a.explain}`);
      L.push(`* **Recommended response:** ${a.respond}`);
      L.push('');
    });
  }

  const attackers = (snapshot.attackers || []).filter((a) => a.alerts > 0);
  if (attackers.length) {
    L.push('## Sources');
    L.push('');
    L.push('| Address | Attempts | Failed | Succeeded | Accounts | Alerts | Blocked until |');
    L.push('|:--|--:|--:|--:|--:|--:|:--|');
    attackers.forEach((a) => L.push(`| ${code(a.ip, 45)} | ${a.attempts} | ${a.failures} | ${a.successes} | ${a.users} | ${a.alerts} | ${a.blockedUntil ? iso(a.blockedUntil) : '-'} |`));
    L.push('');
  }

  if (snapshot.locked?.length) {
    L.push('## Locked accounts');
    L.push('');
    snapshot.locked.forEach((l) => L.push(`* ${code(l.user, 60)} until ${iso(l.until)} (${safe(l.reason)})`));
    L.push('');
  }

  L.push('## Indicators');
  L.push('');
  L.push('Addresses to block or hunt for in other logs:');
  L.push('');
  L.push('```');
  // Only values shaped like IPv4 or IPv6 addresses: a crafted log line must not be able to close the code fence.
  const ips = [...new Set(alerts.map((a) => a.ip).filter((ip) => /^[0-9a-f:.]{3,45}$/i.test(String(ip || ''))))];
  L.push(ips.length ? ips.join('\n') : '(none)');
  L.push('```');
  L.push('');
  return L.join('\n');
}
